
create table membership(
    m_id number generated by default as identity primary key,
    m_name varchar2(30) unique,
    m_duration number(3) check (m_duration > 0) not null,
    m_price number check (m_price >= 0) not null
);


create table staff(
    st_id number generated by default as identity primary key,
    st_name varchar2(30) not null,
    st_phone number unique not null,
    st_email varchar2(40) unique,
    st_address varchar2(30),
    st_hiredate date,
    st_salary number not null check (st_salary >= 0),
    st_role varchar2(30) not null check
        (st_role in ('manager', 'trainer', 'cleaner', 'shopkeeper'))
);


create table equipment (
    e_id number generated by default as identity primary key,
    e_name varchar2(30) not null,
    e_type varchar2(30),
    e_status varchar2(30) not null check
        (e_status in ('available', 'in_use', 'under_repair', 'damaged')),
    e_quantity number not null check (e_quantity >= 0),
    e_buyingdate date
);


create table student(
    s_id number generated by default as identity primary key,
    s_name varchar2(30) unique not null,
    s_level number,
    s_address varchar2(40),
    s_dob date,
    s_phone number unique not null,
    s_email varchar2(30) unique,
    s_memtype varchar2(30),
    s_height number check (s_height > 0),
    s_weight number check (s_weight > 0),
    m_id number not null,
    constraint fk_std_Membership foreign key (m_id)
        references membership (m_id) on delete cascade
);

create table payment (
    p_id number generated by default as identity primary key,
    p_date date default sysdate not null,
    p_amount number not null check (p_amount > 0),
    s_id number not null,
    constraint fk_student_id foreign key (s_id)
        references student (s_id) on delete cascade
);

commit;

create table contest (
    c_id number generated by default as identity primary key,
    c_name varchar2(40) not null,
    c_type varchar2(35),
    c_date date,
    c_location varchar2(40),
    c_winner varchar2(40)
 
);
create table shop (
    sh_name varchar2(20) primary key,
    item_name varchar2(30) not null,
    item_quantity number default 0 check (item_quantity >= 0),
    item_price number not null check (item_price >= 0)
);
commit;
CREATE TABLE training (
    tr_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    tr_name VARCHAR2(50) NOT NULL,
    tr_date DATE DEFAULT SYSDATE NOT NULL,
    s_id NUMBER NOT NULL,
    st_id NUMBER NOT NULL,

    CONSTRAINT pk_training PRIMARY KEY (tr_id),

    CONSTRAINT fk_training_student
        FOREIGN KEY (s_id)
        REFERENCES student(s_id),

    CONSTRAINT fk_training_trainer
        FOREIGN KEY (st_id)
        REFERENCES staff(st_id),

    CONSTRAINT chk_training_name
        CHECK (LENGTH(TRIM(tr_name)) > 0)
);


-- CONTEST PARTICIPATION TABLE

CREATE TABLE contest_participation (
    c_id NUMBER NOT NULL,
    s_id NUMBER NOT NULL,

    CONSTRAINT pk_contest_participation
        PRIMARY KEY (c_id, s_id),

    CONSTRAINT fk_participation_contest
        FOREIGN KEY (c_id)
        REFERENCES contest(c_id),

    CONSTRAINT fk_participation_student
        FOREIGN KEY (s_id)
        REFERENCES student(s_id)
);


-- SALES HISTORY TABLE

CREATE TABLE sales_history (
    sale_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    sh_id NUMBER NOT NULL,
    s_id NUMBER,
    item_quantity NUMBER NOT NULL,
    item_price NUMBER(10,2) NOT NULL,

    total_money NUMBER(12,2)
        GENERATED ALWAYS AS
        (item_quantity * item_price) VIRTUAL,

    CONSTRAINT pk_sales_history PRIMARY KEY (sale_id),

    CONSTRAINT fk_sales_shop
        FOREIGN KEY (sh_id)
        REFERENCES shop(sh_id),

    CONSTRAINT fk_sales_student
        FOREIGN KEY (s_id)
        REFERENCES student(s_id),

    CONSTRAINT chk_sales_quantity
        CHECK (item_quantity > 0),

    CONSTRAINT chk_sales_price
        CHECK (item_price > 0)
);

COMMIT;