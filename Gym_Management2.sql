create table membership(
    m_id number generated by default as identity primary key ,
    m_name varchar2(30) unique,
    m_duration number(3) check (m_duration > 0) not null,
    m_price number check (m_price >= 0) not null
);

    
create table equipment (
    e_id number generated by default as identity primary key,
    e_name varchar2(30) not null,
    e_type varchar2(30),
    e_status varchar2(30) not null check
        (e_status in ('available', 'in_use', 'under_repair', 'damaged')),
    e_quantity number not null check (e_quantity >= 0),
    e_buyingdate date
);


create table payment (
    p_id number generated by default as identity primary key,
    p_date date default sysdate not null,
    p_amount number not null check (p_amount > 0),
    s_id number not null,
    constraint fk_student_id foreign key (s_id)
        references student (s_id) on delete cascade
);


commit;
create table contest (
    c_id number generated by default as identity primary key,
    c_name varchar2(40) not null,
    c_type varchar2(35),
    c_date date,
    c_location varchar2(40),
    c_winner varchar2(40)
 
);
create table shop (
    sh_name varchar2(20) primary key,
    item_name varchar2(30) not null,
    item_quantity number default 0 check (item_quantity >= 0),
    item_price number not null check (item_price >= 0)
);
commit;
