
create table membership(
    m_id number generated by default as identity primary key,
    m_name varchar2(30) unique,
    m_duration number(3) check (m_duration > 0) not null,
    m_price number check (m_price >= 0) not null
);


create table staff(
    st_id number generated by default as identity primary key,
    st_name varchar2(30) not null,
    st_phone number unique not null,
    st_email varchar2(40) unique,
    st_address varchar2(30),
    st_hiredate date,
    st_salary number not null check (st_salary >= 0),
    st_role varchar2(30) not null check
        (st_role in ('manager', 'trainer', 'cleaner', 'shopkeeper'))
);


create table equipment (
    e_id number generated by default as identity primary key,
    e_name varchar2(30) not null,
    e_type varchar2(30),
    e_status varchar2(30) not null check
        (e_status in ('available', 'in_use', 'under_repair', 'damaged')),
    e_quantity number not null check (e_quantity >= 0),
    e_buyingdate date
);


create table student(
    s_id number generated by default as identity primary key,
    s_name varchar2(30) unique not null,
    s_level number,
    s_address varchar2(40),
    s_dob date,
    s_phone number unique not null,
    s_email varchar2(30) unique,
    s_memtype varchar2(30),
    s_height number check (s_height > 0),
    s_weight number check (s_weight > 0),
    m_id number not null,
    constraint fk_std_Membership foreign key (m_id)
        references membership (m_id) on delete cascade
);

create table payment (
    p_id number generated by default as identity primary key,
    p_date date default sysdate not null,
    p_amount number not null check (p_amount > 0),
    s_id number not null,
    constraint fk_student_id foreign key (s_id)
        references student (s_id) on delete cascade
);

commit;
