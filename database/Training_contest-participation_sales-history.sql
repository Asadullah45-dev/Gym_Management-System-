
-- TRAINING TABLE

CREATE TABLE training (
    tr_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    tr_name VARCHAR2(50) NOT NULL,
    tr_date DATE DEFAULT SYSDATE NOT NULL,
    s_id NUMBER NOT NULL,
    st_id NUMBER NOT NULL,

    CONSTRAINT pk_training PRIMARY KEY (tr_id),

    CONSTRAINT fk_training_student
        FOREIGN KEY (s_id)
        REFERENCES student(s_id),

    CONSTRAINT fk_training_trainer
        FOREIGN KEY (st_id)
        REFERENCES staff(st_id),

    CONSTRAINT chk_training_name
        CHECK (LENGTH(TRIM(tr_name)) > 0)
);


-- CONTEST PARTICIPATION TABLE

CREATE TABLE contest_participation (
    c_id NUMBER NOT NULL,
    s_id NUMBER NOT NULL,

    CONSTRAINT pk_contest_participation
        PRIMARY KEY (c_id, s_id),

    CONSTRAINT fk_participation_contest
        FOREIGN KEY (c_id)
        REFERENCES contest(c_id),

    CONSTRAINT fk_participation_student
        FOREIGN KEY (s_id)
        REFERENCES student(s_id)
);


-- SALES HISTORY TABLE

CREATE TABLE sales_history (
    sale_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    sh_id NUMBER NOT NULL,
    s_id NUMBER,
    item_quantity NUMBER NOT NULL,
    item_price NUMBER(10,2) NOT NULL,

    total_money NUMBER(12,2)
        GENERATED ALWAYS AS
        (item_quantity * item_price) VIRTUAL,

    CONSTRAINT pk_sales_history PRIMARY KEY (sale_id),

    CONSTRAINT fk_sales_shop
        FOREIGN KEY (sh_id)
        REFERENCES shop(sh_id),

    CONSTRAINT fk_sales_student
        FOREIGN KEY (s_id)
        REFERENCES student(s_id),

    CONSTRAINT chk_sales_quantity
        CHECK (item_quantity > 0),

    CONSTRAINT chk_sales_price
        CHECK (item_price > 0)
);

COMMIT;
